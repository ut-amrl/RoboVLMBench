REPORTS_DIR = REPO_ROOT / "reports"
COLORS = ["#E69F00", "#0072B2", "#D55E00", "#CC79A7", "#56B4E9", "#F0E442"]  # one per run (Okabe-Ito)
MASK_COLOR = (0, 158, 115)  # shading of ground-truth masks in examples; no run uses green
esc = html.escape


@dataclass
class Run:
    name: str    # "<model>_<mode>", as in outputs/
    engine: str
    info: dict   # run.json: weights, engine, request settings, point format, hardware
    responses: dict[str, Response]

    @property
    def hardware(self) -> str:
        return self.info.get("hardware", "—").replace("NVIDIA ", "")

    @property
    def label(self) -> str:
        """Model and mode, e.g. "Qwen3.8-27B-NVFP4 · think"."""
        mode = self.name.partition("_")[2]
        engine = "" if self.engine == "vllm" else f" ({self.engine})"
        return self.info["repo"].split("/")[-1] + (f" · {mode}" if mode else "") + engine


def find_runs(bench: str) -> list[Run]:
    """Every run of `bench` in outputs/, complete or not."""
    return [
        Run(path.parent.parent.parent.name, path.parent.parent.name, json.loads(path.read_text()),
            load_responses(path.parent / "responses.jsonl"))
        for path in sorted(OUTPUTS_DIR.glob(f"*/*/{bench}/run.json"))
    ]


def complete_runs(runs: list[Run], samples: list) -> list[Run]:
    """The runs that answered every sample; the others are skipped, with a message."""
    complete = []
    for run in runs:
        missing = sum(s.id not in run.responses for s in samples)
        if missing:
            print(f"skipping {run.name} ({run.engine}): {missing} of {len(samples)} questions unanswered")
        else:
            complete.append(run)
    return complete


# Columns every scores table ends with: speed, hardware and failed answers.
SPEED_HEADERS = ('<th>Time per question<br>median</th><th>Time per question<br>90th pct</th>'
                 '<th class="l">Hardware</th><th>Output tokens<br>per question</th><th>Unusable<br>answers</th>')
SPEED_NOTE = """Time per question: from sending a question to receiving the whole answer (reasoning included), with
questions sent one at a time and nothing else on the GPUs. Every image is sent as new, so the server can't reuse
work from earlier questions on the same image, as for a robot whose next question comes with a new camera frame.
Output tokens: median per question, reasoning included. Unusable answers: cut off at the token limit,
unparsable, or failed (hover for which); they count as wrong."""


def speed_cells(run: Run, samples: list, outcomes: dict[str, int]) -> str:
    responses = [run.responses[s.id] for s in samples]
    timing = time_per_question(responses) or {}
    unusable = {k: v for k, v in outcomes.items() if k != "answered" and v}
    return (f'<td>{seconds(timing.get("median"))}</td><td>{seconds(timing.get("p90"))}</td>'
            f'<td class="l">{esc(run.hardware)}</td>'
            f'<td>{statistics.median(r.completion_tokens for r in responses):.0f}</td>'
            f'<td><span title="{esc(", ".join(f"{v} {k}" for k, v in unusable.items()))}">'
            f"{sum(unusable.values())}</span></td>")


def runs_table(runs: list[Run]) -> str:
    rows = "".join(
        f'<tr><td class="l">{esc(run.label)}</td><td class="l"><code>{esc(run.info["repo"])}'
        f'@{run.info["revision"][:7]}</code></td><td class="l">{esc(run.info["engine"])}</td>'
        f'<td class="l wrap"><code>{esc(json.dumps(run.info["request_settings"]))}</code></td>'
        f'<td class="l">{esc(run.info["point_format"])}</td></tr>'
        for run in runs)
    return f"""<h2>Runs</h2>
<div class="scroll"><table>
<tr><th class="l">Model</th><th class="l">Weights</th><th class="l">Engine</th><th class="l">Request settings</th>
<th class="l">Point format</th></tr>
{rows}
</table></div>
<p class="note">Point format: <code>normalized</code> asks for 0–1 coordinates (the benchmark's own instruction
where it has one); <code>qwen</code> asks in Qwen-VL's own format (<code>point_2d</code>, 0–1000) and converts the
points to 0–1 before scoring. Generated by <code>scripts/report.py</code> from <code>outputs/</code>.</p>"""


def draw_points(image: Image.Image, mask: Image.Image, points_per_run: list[list[list[float]]],
                width: int = 420) -> Image.Image:
    """`image` downscaled to `width`, with `mask` shaded and each run's 0-1 points as dots in its color."""
    image = image.convert("RGB")
    image = image.resize((width, round(image.height * width / image.width)), Image.LANCZOS)
    mask = mask.convert("L").resize(image.size, Image.NEAREST)
    image = Image.composite(Image.new("RGB", image.size, MASK_COLOR), image, mask.point(lambda v: 115 if v else 0))
    draw = ImageDraw.Draw(image)
    r = 6
    for i, points in enumerate(points_per_run):
        for x, y in points:  # clamped to the image
            px, py = min(max(x, 0), 1) * (image.width - 1), min(max(y, 0), 1) * (image.height - 1)
            draw.ellipse((px - r, py - r, px + r, py + r), fill=COLORS[i % len(COLORS)], outline="white", width=2)
    return image


def verdicts(runs: list[Run], rows: list[dict]) -> str:
    """A caption list: each run's color, label and ✓/✗ for one sample (`rows`: its per-sample score per run)."""
    marks = []
    for i, (run, row) in enumerate(zip(runs, rows)):
        verdict = ('<span class="ok">✓</span>' if row["correct"] else '<span class="bad">✗</span>'
                   + ("" if row["points"] else " no points"))
        marks.append(f'<li><span class="dot" style="background:{COLORS[i % len(COLORS)]}"></span>'
                     f"{esc(run.label)}: {verdict}</li>")
    return f'<ul>{"".join(marks)}</ul>'


def pick(groups: list[list], n: int) -> list:
    """Up to n items, shared as evenly as possible across the non-empty groups, spread out within each."""
    groups = [g for g in groups if g]
    picks = []
    for i, group in enumerate(groups):
        k = min(len(group), (n - len(picks)) // (len(groups) - i))
        picks += [group[j * len(group) // k] for j in range(k)]
    return picks


def pct(fraction: float | None, digits: int = 1) -> str:
    return "—" if fraction is None else f"{100 * fraction:.{digits}f}"


def seconds(value: float | None) -> str:
    return "—" if value is None else f"{value:.2f} s" if value < 10 else f"{value:.1f} s"


def jpeg_data_url(image: Image.Image, quality: int = 80) -> str:
    buffer = io.BytesIO()
    image.convert("RGB").save(buffer, "JPEG", quality=quality)
    return "data:image/jpeg;base64," + base64.b64encode(buffer.getvalue()).decode()


def page(title: str, body: str) -> str:
    return f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{esc(title)}</title>
<style>{_CSS}</style>
</head>
<body>
<main>
{body}
</main>
</body>
</html>
"""


